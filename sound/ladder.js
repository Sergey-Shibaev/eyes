// Режим «Лесенка»: тихий тик раз в секунду, высота которого показывает, где мы в фазе.
//
// Что слышно с закрытыми глазами:
//   вдох               — тики поднимаются от «пола» (ре первой октавы) к «потолку» (ре второй октавы):
//                        ступенька на каждую секунду, вся октава делится на столько ступенек, сколько секунд в фазе;
//   задержка на вдохе  — ровные тихие тики на «потолке»; последние три громче и ярче: «приготовься»;
//   выдох              — тики спускаются от «потолка» к «полу»;
//   задержка на выдохе — ровные тихие тики на «полу», последние три так же громче.
// Начало каждой фазы (секунда 0) отмечает ядро: колокольчик на вдохе и выдохе, двойной «тук» на задержках.
// Лесенка всегда приходит ровно к высоте следующей метки: после вдоха 4 с звучат ступеньки 1/4, 2/4, 3/4 октавы,
// а четвёртая ступенька — это уже метка следующей фазы на «потолке». По высоте тика слышно, какая доля фазы прошла,
// по счёту тиков — сколько секунд.
//
// Фазы длиннее 12 с тикают раз в 2 с (иначе тиков слишком много и они утомляют), высота по-прежнему считается
// от прошедшей доли фазы. Непрерывных источников нет: каждый тик — одноразовый api.blip со своим stop(),
// поэтому остановка посреди фазы и пропуск фаз (страница спала) не требуют никакой уборки.
(function (root) {
  'use strict';

  const F_LOW = 293.66; // «пол»: ре первой октавы (D4)
  const F_HIGH = 587.33; // «потолок»: ре второй октавы (D5)
  const BELL_TAU = 0.35; // затухание колокольчика ядра: к первому тику (через 1 с) он уже почти стих

  const LONG_PHASE = 12; // фазы длиннее этого, с, тикают реже
  const STEP_SHORT = 1; // шаг тиков в обычной фазе, с
  const STEP_LONG = 2; // шаг тиков в длинной фазе, с
  const READY_TICKS = 3; // столько последних тиков задержки звучат громче: «приготовься»

  // Тик движения (вдох и выдох): синус и 20 % второго обертона, мягкая атака, короткий хвост.
  const TICK_MOVE = { peak: 0.14, attack: 0.008, tau: 0.06, h2: 0.2 };
  // Тик задержки: тот же тембр, но тише — высота не меняется, слушать нечего, нужен только счёт.
  const TICK_HOLD = { peak: 0.08, attack: 0.008, tau: 0.06, h2: 0.2 };
  // Последние тики задержки: громкость как у тика движения и больше обертона — заметнее, но не резче.
  const TICK_READY = { peak: 0.14, attack: 0.008, tau: 0.06, h2: 0.4 };

  // На какие секунды фазы длиной N приходятся тики. Секунда 0 — метка ядра, поэтому тики идут с 1 по N-1.
  // Сетка привязана к КОНЦУ фазы: последний промежуток перед сменой фазы такой же, как все остальные,
  // и по ровному ритму легко угадать момент смены. При шаге 2 с и нечётной длине коротким (1 с) выходит
  // первый промежуток, сразу после метки, а не последний: ритм нигде не ускоряется.
  function tickSeconds(N) {
    const step = N > LONG_PHASE ? STEP_LONG : STEP_SHORT;
    const seconds = [];
    for (let k = N - step; k >= 1; k -= step) seconds.unshift(k);
    return seconds;
  }

  // Высота тика: frac — прошедшая доля фазы (0..1). Вдох — вверх на октаву, выдох — вниз на октаву,
  // задержки стоят на той высоте, куда пришла лесенка.
  function pitch(phase, frac, fLow, fHigh) {
    if (phase === 0) return fLow * Math.pow(2, frac);
    if (phase === 2) return fHigh * Math.pow(2, -frac);
    return phase === 1 ? fHigh : fLow;
  }

  function create(api) {
    return {
      // Вся фаза расписывается сразу, абсолютными временами. ph.t может быть чуть в прошлом — сетку не сдвигаем:
      // первый тик всё равно не раньше чем через 0.75 с.
      phase(ph) {
        const N = Math.round(ph.T);
        if (!(N >= 2) || !Number.isFinite(ph.t)) return; // за 1 с успевает прозвучать только метка ядра
        const hold = ph.phase === 1 || ph.phase === 3;
        const seconds = tickSeconds(N);
        seconds.forEach((k, i) => {
          const ready = hold && seconds.length - i <= READY_TICKS;
          const opts = !hold ? TICK_MOVE : ready ? TICK_READY : TICK_HOLD;
          api.blip(ph.t + k, pitch(ph.phase, k / N, api.fLow, api.fHigh), opts);
        });
      },

      // Непрерывных источников нет. Уже расписанные тики ядро заглушит (api.out затухает и отключается),
      // а каждый осциллятор остановится сам в своё время.
      stop() {},
    };
  }

  root.BreathSound.register({
    id: 'ladder',
    name: 'Лесенка',
    fLow: F_LOW,
    fHigh: F_HIGH,
    bellTau() {
      return BELL_TAU;
    },
    create,
  });
})(typeof self !== 'undefined' ? self : globalThis);
