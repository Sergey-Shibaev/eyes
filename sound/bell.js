// Режим «Тихий колокол»: почти тишина — для вечера и для тех, кому непрерывный звук мешает.
//
// Что слышно:
//   • начало фазы — метка ядра: низкий колокольчик (ре, D4) на вдохе, высокий (ля, A4) на выдохе,
//     двойной «тук» на задержках. Колокольчик здесь затухает долго — примерно на всю фазу,
//     поэтому по тому, насколько он стих, можно чувствовать, сколько фазы прошло;
//   • конец фазы — короткий обратный отсчёт: до трёх тихих «туков» в последние секунды
//     (T−3, T−2, T−1). Высота «туков» — высота СЛЕДУЮЩЕЙ метки: они подводят к грядущему колоколу,
//     и ещё до переключения понятно, что будет дальше (высоко — задержка на вдохе или выдох,
//     низко — вдох или задержка на выдохе).
// Больше ничего: никаких непрерывных источников, поэтому stop() останавливать нечего —
// одноразовые «туки» сами получают stop() внутри api.blip, а остаток глушит ядро через api.out.
//
// Крайние случаи:
//   T = 1      — отсчёта нет (floor(1/2) = 0): на секунду хватает одной метки;
//   T = 2..3   — один «тук» за секунду до конца;  T = 4..5 — два;  T >= 6 — три;
//   T = 60     — колокол стихает за первые ~15 с, дальше тишина до трёх «туков» в конце;
//   без задержек и при двух фазах в цикле — всё так же: высота берётся из ph.nextPhase;
//   страница спала — ядро просто не вызывает phase(); состояния между фазами режим не хранит,
//   так что «застрять» или щёлкнуть при возобновлении нечему.
(function (root) {
  'use strict';

  const F_LOW = 293.66; // ре первой октавы (D4): вдох и задержка на выдохе
  const F_HIGH = 440; // ля первой октавы (A4): выдох и задержка на вдохе

  // Затухание колокольчика: четверть длины фазы, но не короче обычного звона и не дольше 4 с.
  const BELL_TAU_SHARE = 1 / 4;
  const BELL_TAU_MIN = 0.35;
  const BELL_TAU_MAX = 4;

  // Обратный отсчёт в конце фазы.
  const MAX_TICKS = 3; // не больше трёх «туков»
  const TICK_STEP = 1; // ровно секунда между «туками» — темп никогда не ускоряется
  const SECONDS_PER_TICK = 2; // один «тук» на каждые две секунды фазы: n = min(3, floor(T / 2))
  const TICK = Object.freeze({ peak: 0.08, attack: 0.005, tau: 0.03, h2: 0.3 }); // синус + 30 % второй гармоники

  const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

  function bellTau(T) {
    if (!Number.isFinite(T)) return BELL_TAU_MIN;
    return clamp(T * BELL_TAU_SHARE, BELL_TAU_MIN, BELL_TAU_MAX);
  }

  // Сколько «туков» помещается в фазу длиной T секунд.
  function tickCount(T) {
    if (!(T > 0) || !Number.isFinite(T)) return 0;
    return Math.min(MAX_TICKS, Math.floor(T / SECONDS_PER_TICK));
  }

  // Высота метки, которой начнётся следующая фаза (то же правило, что и у ядра в mark()).
  function nextMarkPitch(api, nextPhase) {
    const high = nextPhase === 1 || nextPhase === 2;
    return high ? api.fHigh : api.fLow;
  }

  function create(api) {
    return {
      // Вся фаза расписывается сразу, абсолютными временами аудиочасов.
      // ph.t может быть чуть в прошлом — сетку не сдвигаем: первый «тук» не раньше ph.t + 1 с, он всегда в будущем.
      phase(ph) {
        const n = tickCount(ph.T);
        if (!n || !Number.isFinite(ph.t)) return;
        const f = nextMarkPitch(api, ph.nextPhase);
        for (let i = n; i >= 1; i--) {
          api.blip(ph.t + ph.T - i * TICK_STEP, f, TICK); // секунды T−n … T−1
        }
      },

      // Непрерывных источников нет: уже расписанные «туки» гасит ядро (затухание api.out),
      // а их осцилляторы получили свой stop() при создании.
      stop() {},
    };
  }

  root.BreathSound.register({
    id: 'bell',
    name: 'Тихий колокол',
    fLow: F_LOW,
    fHigh: F_HIGH,
    bellTau,
    create,
  });
})(typeof self !== 'undefined' ? self : globalThis);
