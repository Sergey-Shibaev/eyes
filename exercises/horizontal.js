// Упражнение «Влево-вправо»: взгляд ходит по горизонтали — точка плавно едет
// от края к краю и останавливается в крайних положениях. Вертикали здесь нет
// намеренно: упражнение про горизонталь, вертикаль закрывают «Круги» и «Восьмёрка».
//
// Почему всё так неспешно. Скорость считается в долях поля, где поле от -1 до 1,
// то есть по ширине это 2 доли; tests/exercise.test.js не пропускает больше
// 0,5 доли в секунду, а комфортным считает 0,25. Важно: тест меряет мгновенную
// скорость, а разгон с торможением (см. ease ниже) поднимают её в 1,33 раза
// над средней. Поэтому переезд через всё поле не может быть быстрее 5,4 секунды:
// за 4 секунды средняя была бы ровно 0,5, но пик дошёл бы до 0,67 — тест завернёт.
// Здесь переезд занимает 8 секунд: 0,25 доли/с в среднем, 0,33 на пике.
// Взгляд ведёт точку ровно, без догоняющих скачков.
//
// Полное описание контракта — в exercises/registry.js.
(function () {
  'use strict';

  // Какая доля отрезка уходит на разгон (столько же — на торможение).
  // При 0,25 пик скорости всего в 1,33 раза выше средней: точка трогается
  // и останавливается мягко, но не тратит лишние секунды на «подползание»
  // к краю, как было бы с синусоидой (у той пик в 1,57 раза выше средней).
  const RAMP = 0.25;
  const PEAK = 1 / (1 - RAMP); // 1,333 — во столько раз пиковая скорость выше средней

  // Трапециевидный профиль скорости: разгон — ровное движение — торможение.
  // Возвращает пройденную долю пути (0..1) в момент p (0..1).
  function ease(p) {
    if (p <= 0) return 0;
    if (p >= 1) return 1;
    if (p < RAMP) return (PEAK * p * p) / (2 * RAMP);
    if (p <= 1 - RAMP) return PEAK * (RAMP / 2 + (p - RAMP));
    return 1 - (PEAK * (1 - p) * (1 - p)) / (2 * RAMP);
  }

  // Отрезки, из которых собирается путь точки.
  const move = (x, dur) => ({ x, dur }); // переехать в x за dur секунд
  const hold = (dur) => ({ x: null, dur }); // постоять там, где стоим (не меньше секунды)

  // Собирает шаг слежения из отрезков: остановки и переезды идут одной
  // непрерывной линией, поэтому внутри шага точка никогда не прыгает.
  function sweeps(label, startX, parts) {
    const dur = parts.reduce((sum, part) => sum + part.dur, 0);
    return {
      kind: 'track',
      label,
      dur,
      at(p) {
        let left = p * dur;
        let from = startX;
        for (const part of parts) {
          const to = part.x === null ? from : part.x;
          if (left <= part.dur) return [from + (to - from) * ease(left / part.dur), 0];
          left -= part.dur;
          from = to;
        }
        return [from, 0];
      },
    };
  }

  EyeExercises.register({
    id: 'horizontal',
    name: 'Влево-вправо',
    note: 'Когда долго смотрели в одну точку экрана и хочется размять взгляд.',
    // Аудит 2026-09-21: ни одного контролируемого исследования слежения за точкой у здоровых людей.
    evidence: 'none',
    evidenceNote: 'Движение взгляда вправо-влево — приятная смена нагрузки и повод оторваться от текста. Ни одно исследование не показало, что оно само по себе снимает усталость глаз.',
    steps: [
      // Точки ещё нет: сначала объясняем главное правило упражнения.
      { kind: 'rest', label: 'Голову не поворачивайте', dur: 6 },

      // Разминка: половина ширины поля, короткие остановки по секунде.
      // Самый быстрый переезд здесь — 0,2 доли/с в среднем и 0,27 на пике,
      // глаз входит в темп.
      sweeps('Следите за точкой', 0, [
        move(-0.5, 3),
        hold(1),
        move(0.5, 5),
        hold(1),
        move(-0.5, 5),
        hold(1),
      ]),

      // Полный размах. Первое число, -0.5, обязано совпадать с концом предыдущего
      // шага: иначе при смене надписи точка перескочит, а тест такого не ловит —
      // он проверяет разрывы только внутри шага. Правите шаг выше — правьте и здесь.
      // Остановки у краёв по 2 секунды: взгляд успевает дойти до края и замереть.
      // Последняя короче, на секунду: сразу за ней идёт отдых.
      sweeps('Задержитесь в крайних точках', -0.5, [
        move(-1, 2),
        hold(2),
        move(1, 8),
        hold(2),
        move(-1, 8),
        hold(1),
      ]),

      // Отдых после двух шагов слежения — раньше, чем требует контракт.
      { kind: 'rest', label: 'Посмотрите вдаль', dur: 10 },

      // Последний заход: одно длинное пересечение и возврат в центр,
      // чтобы упражнение закончилось на спокойном прямом взгляде.
      sweeps('Ещё раз, до самого края', -1, [
        hold(1),
        move(1, 8),
        hold(2),
        move(0, 4),
        hold(1),
      ]),

      { kind: 'blink', label: 'Поморгайте', dur: 8 },
      { kind: 'rest', label: 'Отдохните, смотрите вдаль', dur: 10 },
    ],
  });
})();
