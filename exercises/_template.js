// ОБРАЗЕЦ УПРАЖНЕНИЯ. Файлы, начинающиеся с подчёркивания, в приложение не подключаются:
// скопируйте этот файл под своим именем, например exercises/circle.js, и добавьте строку
// <script src="exercises/circle.js"></script> в index.html рядом с остальными упражнениями.
//
// Полное описание контракта — в exercises/registry.js.
(function () {
  'use strict';

  EyeExercises.register({
    id: 'template',
    name: 'Образец',
    note: 'Показывает все три вида шагов. Скопируйте файл и напишите своё.',
    steps: [
      {
        // Плавное слежение: точка едет по кругу.
        // Круг длиной 2π долей поля: за 16 секунд получается 0,39 поля в секунду —
        // в пределах, которые проверяет tests/exercise.test.js.
        kind: 'track',
        label: 'Следите за точкой',
        dur: 16,
        at(p) {
          const angle = p * 2 * Math.PI;
          return [Math.cos(angle), Math.sin(angle)];
        },
      },
      {
        // Неподвижная точка: взгляд стоит в одном положении. Скачок в новое место —
        // это начало нового шага, поэтому at здесь возвращает постоянное значение.
        kind: 'track',
        label: 'Смотрите влево',
        dur: 3,
        at: () => [-1, 0],
      },
      {
        kind: 'track',
        label: 'Смотрите вправо',
        dur: 3,
        at: () => [1, 0],
      },
      {
        // Отдых: точка спрятана, работает только надпись и звук.
        kind: 'rest',
        label: 'Посмотрите вдаль',
        dur: 10,
      },
      {
        kind: 'blink',
        label: 'Поморгайте медленно',
        dur: 6,
      },
    ],
  });
})();
