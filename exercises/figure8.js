// Восьмёрка: точка идёт «знаком бесконечности» — наискось через центр, петля вправо и петля влево.
// Сначала в одну сторону, потом, после взгляда вдаль, тот же путь в обратную.
//
// Полное описание контракта — в exercises/registry.js.
(function () {
  'use strict';

  const TAU = 2 * Math.PI;

  // Лежачая восьмёрка (лемниската Жероно): x = sin t, y = sin t · cos t.
  // Размах по вертикали вдвое с лишним меньше горизонтального (±0,45 против ±1):
  // так восьмёрка выглядит лежачей, а не раздутой. Поле в приложении квадратное.
  const X_AMP = 1;
  const Y_AMP = 0.9; // настоящий размах по вертикали — половина этого числа
  function point(t) {
    return [X_AMP * Math.sin(t), Y_AMP * Math.sin(t) * Math.cos(t)];
  }

  // Ход у восьмёрки неравномерный: на перекрестье в центре точка разгоняется примерно
  // вдвое против петель по краям. Поэтому ведём её не по параметру t, а по длине пути —
  // тогда скорость постоянна, без рывка в середине, и её легко удержать в комфортной
  // четверти поля в секунду.
  //
  // Таблица считается один раз при загрузке файла: по доле пройденного пути k / SIZE
  // она даёт параметр t. Во время упражнения остаётся только взять значение и сгладить
  // между соседними — на кадре считается пара тригонометрий, а не длина пути заново.
  const FINE = 4096; // на столько кусочков делим кривую, чтобы измерить её длину
  const SIZE = 512; // столько строк в готовой таблице
  const path = buildPath();

  function buildPath() {
    const cum = [0]; // накопленная длина пути к каждому кусочку
    let prev = point(0);
    for (let i = 1; i <= FINE; i++) {
      const cur = point((i / FINE) * TAU);
      cum.push(cum[i - 1] + Math.hypot(cur[0] - prev[0], cur[1] - prev[1]));
      prev = cur;
    }
    const length = cum[FINE];

    const ts = [];
    let i = 0;
    for (let k = 0; k <= SIZE; k++) {
      const want = (k / SIZE) * length;
      while (i < FINE - 1 && cum[i + 1] < want) i++;
      const span = cum[i + 1] - cum[i];
      const frac = span > 0 ? (want - cum[i]) / span : 0;
      ts.push(((i + frac) / FINE) * TAU);
    }
    return { ts, length };
  }

  // Где точка, когда пройдена доля s всего пути (s идёт от 0 до 1).
  function along(s) {
    const k = Math.min(SIZE, Math.max(0, s * SIZE));
    const i = Math.min(SIZE - 1, Math.floor(k));
    const frac = k - i;
    return point(path.ts[i] + (path.ts[i + 1] - path.ts[i]) * frac);
  }

  // Длина восьмёрки — 5,80 доли поля. За 24 секунды это 0,24 поля в секунду:
  // медленно настолько, что взгляд ведёт точку без догоняющих скачков.
  const LAP = 24;

  EyeExercises.register({
    id: 'figure8',
    name: 'Восьмёрка',
    note: 'Плавная восьмёрка для паузы, когда глаза устали держаться за строчки.',
    steps: [
      // Первый шаг — просто пауза перед стартом: сесть и перестать вертеть головой.
      { kind: 'rest', label: 'Голову держите неподвижно', dur: 6 },
      { kind: 'track', label: 'Следите за точкой', dur: LAP, at: (p) => along(p) },
      // Между кругами обязательный отдых: взгляд вдаль снимает напряжение ближнего зрения.
      { kind: 'rest', label: 'Посмотрите вдаль', dur: 12 },
      // Тот же путь в обратную сторону: доля пути отсчитывается с конца.
      // В надписи снова есть «следите»: перед этим шагом был отдых, глаза уходили от экрана,
      // и одного «в обратную сторону» мало, чтобы понять, что точку опять надо вести.
      { kind: 'track', label: 'Следите за точкой в обратную сторону', dur: LAP, at: (p) => along(1 - p) },
      { kind: 'blink', label: 'Поморгайте, не спеша', dur: 8 },
      { kind: 'rest', label: 'Посмотрите вдаль, дальше 6 метров', dur: 12 },
    ],
    // Всего 86 секунд: 48 из них слежение, остальное — отдых.
  });
})();
