// Гимнастика для век по японскому офтальмологу Рейко Арите.
//
// Исследование: Arita и др., The Ocular Surface, 2025 (n=100, в основном люди с сухим глазом).
// Упражнение делали сразу после увлажняющих капель, 5 раз в день, три дня, и сравнивали с одними каплями:
// жалобы и устойчивость слёзной плёнки стали лучше. Но испытание одно, короткое, без плацебо,
// с каплями, а у людей без сухости глаз улучшилась только ширина раскрытия век.
// Скептическая проверка оценила доказательства для приложения как слабые — так и помечено ниже.
// По сути это вариант упражнения «Моргание» с дополнительным прищуром нижними веками.
//
// Порядок движений — по описанию самой Ариты: закрыть глаза на 2 секунды, дважды легко моргнуть,
// крепко зажмуриться, не морща лоб, открыть глаза и прищуриться «как от яркого света»,
// приподняв нижние веки. Сколько держать зажмуривание и прищур, в источниках не сказано:
// 3 секунды — наш выбор. Пять подходов подряд — как в популярном описании метода.
//
// Трудность: на двух шагах глаза закрыты, и следующую надпись не прочесть. Поэтому порядок
// показан заранее, на вступительных шагах, подходы одинаковые и ритм быстро запоминается,
// а смену шага отмечает звук (включите его в настройках).
(function () {
  'use strict';

  const SETS = 5;

  function steps() {
    const list = [
      { kind: 'rest', label: 'Порядок: закрыть, моргнуть дважды, зажмуриться, прищуриться', dur: 8 },
      { kind: 'rest', label: 'Лоб не морщите. Смену шага подскажет звук', dur: 5 },
    ];
    for (let i = 0; i < SETS; i++) {
      list.push(
        { kind: 'rest', label: 'Закройте глаза', dur: 2 },
        // Два лёгких моргания: темп 1 с на моргание, отсчёт покажет 2 и 1
        { kind: 'blink', label: 'Моргните дважды', dur: 2, period: 1 },
        { kind: 'rest', label: 'Крепко зажмурьтесь', dur: 3 },
        { kind: 'rest', label: 'Прищурьтесь, как от яркого света', dur: 3 },
        { kind: 'rest', label: 'Расслабьтесь', dur: 2 },
      );
    }
    list.push({ kind: 'rest', label: 'Посмотрите вдаль, моргайте свободно', dur: 10 });
    return list;
  }

  EyeExercises.register({
    id: 'eyelids',
    name: 'Гимнастика для век',
    note: 'Если пользуетесь увлажняющими каплями — делайте сразу после них. После операции на глазах и при глаукоме сначала спросите врача: сильное зажмуривание ненадолго повышает давление в глазу.',
    evidence: 'weak',
    evidenceNote: 'В одном коротком исследовании 2025 года взрослые, в основном с сухим глазом, делали эту гимнастику после увлажняющих капель 5 раз в день три дня, и жалобы уменьшились сильнее, чем от одних капель. У людей без сухости глаз и без капель польза не проверена.',
    steps,
  });
})();
