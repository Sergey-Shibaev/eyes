// Правило 20-20-20 — перерыв в работе с экраном.
//
// Суть правила: каждые 20 минут за экраном 20 секунд смотреть на что-нибудь
// дальше 6 метров (20 футов). Числа в правиле круглые и удобные для запоминания,
// а не отмеренные: чем именно хороши 20 секунд, а не 15 или 40, никто не показал.
// Поэтому здесь взгляд вдаль чуть длиннее — около 27 секунд за круг: лишние
// секунды ничего не стоят. Обещаем ровно то, что это и есть: перерыв, а не лечение.
//
// Почему всего 40 секунд: упражнение задумано как короткий блок, который
// повторяется по кругу (приложение крутит его, пока не нажмёшь «Остановить»).
// Один круг — это перерыв на бегу, три круга — спокойные две минуты.
//
// Шагов нарочно мало: во время перерыва человек смотрит в окно, а не в экран,
// и смену шага замечает по звуку. Слышно при этом не всё: в app.js все шаги
// отдыха звучат одинаково, поэтому переходы на 5-й и на 40-й секунде на слух
// не отличить. Не беда — по обе стороны от них просят одного и того же.
// Отдельно звучат только начало и конец моргания, а это и есть те два момента,
// ради которых стоит прислушиваться. Каждая лишняя надпись — лишний повод
// вернуться взглядом к телефону.
//
// Точки здесь нет ни на одном шаге. Это самое спокойное упражнение в списке:
// его же стоит выбирать, когда следить за точкой не хочется.
(function () {
  'use strict';

  EyeExercises.register({
    id: 'rule20',
    name: 'Правило 20-20-20',
    note: 'Каждые 20 минут за экраном: отложить телефон и посмотреть вдаль.',
    // Проверено в аудите 2026-09-21: частые перерывы в одном небольшом испытании помогали,
    // а сами числа 20-20-20 — нет (Johnson и Rosenfield 2023; Talens-Estarelles 2023).
    evidence: 'weak',
    evidenceNote: 'В одном небольшом исследовании перерывы каждые 10 минут уменьшали раздражение и усталость глаз по сравнению с работой без перерывов, а в другом 20-секундные перерывы не помогли ни при какой частоте. Числа «20-20-20» не доказаны, так что это просто полезный перерыв.',
    steps: [
      {
        // Пять секунд на то, чтобы опустить телефон и найти, куда смотреть.
        // Без этого шага длинный взгляд вдаль начинается с суеты.
        kind: 'rest',
        label: 'Отложите телефон, расправьте плечи',
        dur: 5,
      },
      {
        // Главный шаг. 20 секунд из названия правила держим как нижнюю границу:
        // меньше — это уже не перерыв, а больше не жалко.
        // 6 метров — это те самые 20 футов: окно, дальняя стена, коридор.
        kind: 'rest',
        label: 'Смотрите вдаль, дальше 6 метров',
        dur: 20,
      },
      {
        // Осознанное моргание: после долгого экрана моргают реже, глаза подсыхают.
        // Темп по умолчанию — 2,4 с на моргание, за 8 секунд получается три моргания;
        // знак в центре поля моргает в этом темпе, а цифра рядом с надписью считает,
        // сколько морганий осталось.
        // Полный проверенный протокол моргания — отдельное упражнение, exercises/blink.js.
        kind: 'blink',
        label: 'Поморгайте, зажмуриваясь',
        dur: 8,
      },
      {
        // Хвост перерыва: глаза уже отпустило, возвращаемся к дальнему предмету.
        // Заодно этот шаг сшивает круг — дальше снова пойдёт первый шаг.
        kind: 'rest',
        label: 'Ещё раз вдаль, не напрягайтесь',
        dur: 7,
      },
    ],
  });
})();
