// Упражнение «Круги»: плавное слежение — круг в одну сторону, круг в другую, потом плоский овал.
// Полное описание контракта — в exercises/registry.js.
(function () {
  'use strict';

  const TAU = 2 * Math.PI;

  // Поле под точкой у телефона в портрете вытянуто по вертикали: одна и та же доля поля
  // по вертикали физически длиннее, чем по горизонтали. Замеры высоты поля к его ширине:
  // 1,28 на экране 360×640, 1,30 на 375×667, 1,72 на 375×812, 1,78 на 430×932.
  // Берём среднее по этому разбросу. С такой поправкой круг выглядит кругом на любом
  // из них (ошибка формы не больше 20%), а без неё — овалом стоймя. Заодно выравнивается
  // скорость: без поправки точка по вертикали проходила бы те же доли поля
  // почти вдвое быстрее в миллиметрах, чем по горизонтали.
  const FIELD_ASPECT = 1.55;

  // Точка на окружности или овале.
  //   rx, ry     — полуоси в долях поля (1 — до самого края);
  //   dir        —  1 по часовой стрелке, -1 против;
  //   startAngle — 0 старт сверху, -π/2 старт слева.
  // Быстрее всего точка идёт на концах большей полуоси: TAU * max(rx, ry) / dur долей поля
  // в секунду. Это и есть число, которое меряет tests/exercise.test.js (предел 0,5,
  // спокойный темп — около 0,25), и отсюда берутся все dur ниже.
  function ringAt(rx, ry, dir, startAngle) {
    return function (p) {
      const a = startAngle + dir * p * TAU;
      return [rx * Math.sin(a), -ry * Math.cos(a)];
    };
  }

  EyeExercises.register({
    id: 'circle',
    name: 'Круги',
    note: 'Спокойное слежение по кругу — когда хочется оторваться от строчек и размять взгляд.',
    steps: [
      {
        // Короткая пауза перед началом: успеть сесть удобно и перестать вертеть головой.
        kind: 'rest',
        label: 'Сядьте удобно, голову не поворачивайте',
        dur: 6,
      },
      {
        // Круг: по горизонтали 0,9 поля, по вертикали столько же в миллиметрах,
        // то есть 0,9 / FIELD_ASPECT ≈ 0,58 доли. Оборот за 18 с — это 0,31 доли
        // поля в секунду при пределе теста 0,5 (быстрее 11 с оборот делать уже нельзя).
        // На экране выходит около 50 пикселей в секунду по обеим осям — ровно столько же,
        // сколько в «Влево-вправо»: взгляд ведёт точку без догоняющих скачков.
        // Горизонтальная полуось 0,9, а не 1,0: у точки есть ореол, ему нужен край поля.
        kind: 'track',
        label: 'Следите за точкой',
        dur: 18,
        at: ringAt(0.9, 0.9 / FIELD_ASPECT, 1, 0),
      },
      {
        // Тот же круг в обратную сторону. Начинается там же, где закончился предыдущий
        // (сверху), — смены направления взгляд не теряет, разрыва между шагами нет.
        kind: 'track',
        label: 'По кругу в другую сторону',
        dur: 18,
        at: ringAt(0.9, 0.9 / FIELD_ASPECT, -1, 0),
      },
      {
        // Отдых после двух шагов слежения: подряд их должно быть не больше трёх.
        kind: 'rest',
        label: 'Посмотрите вдаль',
        dur: 12,
      },
      {
        // Плоский овал: старт слева, по часовой стрелке. Вертикальная полуось вдвое
        // меньше, чем у круга выше, и с той же поправкой на вытянутость поля — значит
        // и на экране фигура ровно вдвое более плоская, а не «почти круг», как вышло бы
        // без поправки. Скорость по большей полуоси: TAU·0,95 / 18 = 0,33 доли в секунду.
        kind: 'track',
        label: 'Ведите взгляд по овалу',
        dur: 18,
        at: ringAt(0.95, 0.95 / (2 * FIELD_ASPECT), 1, -Math.PI / 2),
      },
      {
        // Моргание после слежения: при работе с экраном моргают реже, глаза подсыхают.
        kind: 'blink',
        label: 'Поморгайте',
        dur: 8,
      },
      {
        // Финал — взгляд вдаль. 10 с вместо привычных 20: перед этим уже был перерыв,
        // и всё упражнение укладывается в 90 с.
        kind: 'rest',
        label: 'Посмотрите вдаль, дальше 6 метров',
        dur: 10,
      },
    ],
  });
})();
