// Осознанное моргание — упражнение для глаз, которые сохнут от экрана.
// За экраном моргают реже обычного и часто не до конца, и слёзная плёнка обновляется хуже;
// здесь мы моргаем нарочно, не спеша и до полного закрытия.
//
// Точки в упражнении нет совсем — только надпись, знак по центру и звук.
// Поэтому оно годится и тем, кому от движущейся точки становится нехорошо.
//
// Полное описание контракта — в exercises/registry.js.
(function () {
  'use strict';

  // Ритм задаёт знак на экране: в styles.css он мигает анимацией «wink 2.4s»,
  // то есть одно моргание = 2,4 секунды. Длительности шагов берём кратными этому числу,
  // иначе шаг оборвётся на середине мигания и картинка разойдётся с надписью.
  // Знак показывает только, КОГДА моргнуть; как именно — сказано в надписи шага.
  // При системной настройке «уменьшить движение» знак не мигает вовсе (так велит styles.css):
  // тогда ритм человек задаёт сам, и шаг от этого не ломается.
  const REP = 2.4; // секунды на одно моргание
  const SET = Math.round(REP * 5); // 12 с — ровно пять морганий подряд
  const PAUSE = 5; // пауза между подходами; заодно один полный цикл анимации «breathe 5s»

  // Три подхода по пять — пятнадцать морганий за упражнение.
  // Число взято не из исследования: столько помещается в минуту и не успевает надоесть.
  // Твёрдо известно другое: за экраном моргают реже и не до конца, а полное неторопливое
  // моргание смачивает глаз. Помогает это, только пока моргаешь, — поэтому упражнение
  // и сделано коротким: минуту нетрудно повторить пару раз за день.
  EyeExercises.register({
    id: 'blink',
    name: 'Моргание',
    note: 'Когда от экрана сохнут и устают глаза — пятнадцать медленных морганий.',
    steps: [
      // Начинаем с паузы: со сжатыми веками и поднятыми плечами спокойно моргать не выйдет.
      { kind: 'rest', label: 'Расслабьте лицо и плечи', dur: PAUSE },

      // Первый подход — разминка: обычные, ненапряжённые моргания в спокойном ритме.
      { kind: 'blink', label: 'Моргайте легко, не спеша', dur: SET },
      { kind: 'rest', label: 'Пауза. Смотрите свободно', dur: PAUSE },

      // Второй — полное закрытие: от привычки моргать наполовину глаза сохнут сильнее.
      { kind: 'blink', label: 'Закрывайте глаза полностью', dur: SET },
      { kind: 'rest', label: 'Пауза. Расслабьте веки', dur: PAUSE },

      // Третий — мягкое зажмуривание. Именно мягкое: сильно жмуриться незачем.
      { kind: 'blink', label: 'Моргайте и мягко жмурьтесь', dur: SET },

      // В конце — взгляд вдаль: перерыв для глаз и спокойный выход из упражнения.
      // 10 с — два цикла «breathe», хватает, чтобы оторваться от экрана и найти окно.
      { kind: 'rest', label: 'Посмотрите вдаль, дальше 6 метров', dur: 10 },
    ],
  });
})();
