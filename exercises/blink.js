// Осознанное моргание с зажмуриванием — упражнение для глаз, которые сохнут от экрана.
// За экраном моргают реже обычного и часто не до конца, и слёзная плёнка обновляется хуже.
//
// Это единственное упражнение в приложении с настоящим испытанием за спиной.
// Wolffsohn и др., Contact Lens & Anterior Eye, 2025 (n=98, люди с синдромом сухого глаза):
// лучшей оказалась схема «закрыть — зажмуриться — открыть», 15 повторов, 3 раза в день, две недели.
// Именно зажмуривание снижало частоту жалоб, а 15 повторов работали лучше 5.
// Польза держится, пока упражнение делают: через две недели после отмены всё вернулось.
// Людей без жалоб на сухость не изучали — об этом честно сказано в evidenceNote.
//
// Сколько секунд закрывать, жмуриться и открывать, в исследовании не задано.
// Мы берём неторопливый цикл в 4 секунды: знак в центре поля плавно закрывается,
// держится закрытым и открывается (period: 4 задаёт темп его анимации).
//
// Точки в упражнении нет совсем — только надпись, знак и звук.
// Поэтому оно годится и тем, кому от движущейся точки становится нехорошо.
(function () {
  'use strict';

  const CYCLE = 4; // секунд на один цикл «закрыть — зажмуриться — открыть»
  const SET = 5 * CYCLE; // подход из пяти циклов; три подхода — 15 повторов, как в исследовании
  const PAUSE = 5;

  // Одна и та же надпись во всех подходах: цифра рядом считает оставшиеся повторы.
  const DO = 'Закройте, зажмурьтесь, откройте';

  EyeExercises.register({
    id: 'blink',
    name: 'Моргание',
    note: 'Когда от экрана сохнут глаза. Лучше всего — три раза в день. Жмурьтесь мягко; после операции на глазах сначала спросите врача.',
    evidence: 'moderate',
    evidenceNote: 'В небольших исследованиях 2025 года 15 медленных морганий с лёгким зажмуриванием три раза в день в течение двух недель уменьшали сухость и дискомфорт у людей с синдромом сухого глаза. Польза держится, только пока упражнение делают; людям без жалоб на сухость оно, скорее всего, ничего не даст.',
    steps: [
      // Короткое вступление: как жмуриться. Во время самих повторов читать некогда.
      { kind: 'rest', label: 'Жмурьтесь мягко, лоб не морщите', dur: 6 },

      { kind: 'blink', label: DO, dur: SET, period: CYCLE },
      { kind: 'rest', label: 'Пауза, смотрите свободно', dur: PAUSE },

      { kind: 'blink', label: DO, dur: SET, period: CYCLE },
      { kind: 'rest', label: 'Пауза, расслабьте веки', dur: PAUSE },

      { kind: 'blink', label: DO, dur: SET, period: CYCLE },

      // В конце — взгляд вдаль: спокойный выход из упражнения.
      { kind: 'rest', label: 'Посмотрите вдаль, моргайте свободно', dur: 10 },
    ],
  });
})();
